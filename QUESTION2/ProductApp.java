    private void btnProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcessActionPerformed
       String CusName = txtName.getText();
       String ProductName = jComboProduct.getSelectedItem().toString();
       double price = Double.parseDouble(txtPrice.getText());
       
       
       final double VAT = 0.15 * price;
       double commision = VAT * price + price;
       double  total = VAT + commision + price;
       btnProcess.setText("Customer Name" + CusName +
                           "\n Product: " + ProductName +
                            "VAT" + VAT +
                            "\n COMMISSION: " + commision +
                             "TOTAL: " + total);
    }//GEN-LAST:event_btnProcessActionPerformed
 
